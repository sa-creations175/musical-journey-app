/**
 * The phrase the prototype plays, for all 130 cards, in MIDI.
 *
 * =====================================================================
 * PRODUCED BY THE PROTOTYPE'S OWN PLAYBACK ARITHMETIC.
 *
 * `docs/modal-improvisation-prototype_1.html` builds a `seq` of pitch
 * classes and then sounds it: `playChord(rootPc, quality, …)` voices
 * the chord as [r, r+12, r+12+third, r+19] over r = 48 + rootPc, with
 * r+22 added for a dominant; the run is `base + pc` for each pitch
 * class in it, where base is 60 if the chord's root is above F and 72
 * otherwise. Both were run here rather than described, so what is
 * pinned is what a reader heard.
 *
 * ABSOLUTE MIDI, NOT SEMITONES FROM A ROOT. `cardAudio` describes a
 * sound relative to `rootMidi`, and a fixture in the same terms would
 * be checking the app's arithmetic against itself. The test adds
 * `rootMidi` back on and compares actual pitches, which is the only
 * form the two sides can disagree in.
 *
 * The `parse()` repair that renamed thirty borrowed chords does not
 * reach here: the sequence is built from pitch classes throughout, so
 * every number below is identical before and after it.
 * =====================================================================
 */
export interface PrototypeSegment {
  /** The chord, held under the run. */
  chord: readonly number[];
  /** The scale run over it — seven notes and the octave. */
  run: readonly number[];
}

export interface PrototypePhrase {
  key: string;
  chord: string;
  /** Home, the card's chord, where it lands (borrowed only), home. */
  segments: readonly PrototypeSegment[];
}

